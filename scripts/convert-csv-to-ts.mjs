import { readFileSync, writeFileSync } from 'fs'
import { join } from 'path'

// Read CSV file
const csvPath = join(process.cwd(), 'public', 'data', 'tests.csv')
const csvContent = readFileSync(csvPath, 'utf-8')

// Parse CSV
const lines = csvContent.trim().split('\n')
const headers = lines[0].split(',').map(h => h.trim().replace(/^"|"$/g, ''))

const tests = []
for (let i = 1; i < lines.length; i++) {
  const line = lines[i]
  if (!line.trim()) continue

  const values = {}
  let current = ''
  let inQuotes = false
  let colIndex = 0

  for (let j = 0; j < line.length; j++) {
    const char = line[j]
    if (char === '"') {
      inQuotes = !inQuotes
    } else if (char === ',' && !inQuotes) {
      values[headers[colIndex]] = current.replace(/^"|"$/g, '')
      current = ''
      colIndex++
    } else {
      current += char
    }
  }
  values[headers[colIndex]] = current.replace(/^"|"$/g, '')

  tests.push({
    id: values.test_id || '',
    name: values.test_name || '',
    price: parseInt(values.price) || 0,
    mrp: parseInt(values.price) || 0,
    description: values.short_description || '',
    category: values.category_id || 'General Lab Tests',
    homeCollection: values.home_collection_available === 'Yes',
    turnaroundTime: values.turnaround_time || '24 hours',
  })
}

// Generate TypeScript file
const tsContent = `// AUTO-GENERATED FILE: All 694 tests from CSV
// This file was generated by scripts/convert-csv-to-ts.mjs
// DO NOT EDIT MANUALLY

export interface LabTest {
  id: string
  name: string
  price: number
  mrp: number
  description: string
  category: string
  homeCollection: boolean
  turnaroundTime: string
}

export const ALL_TESTS: LabTest[] = ${JSON.stringify(tests, null, 2)}

export const getTestById = (id: string): LabTest | undefined => {
  return ALL_TESTS.find(test => test.id === id)
}

export const getTestsByCategory = (category: string): LabTest[] => {
  return ALL_TESTS.filter(test => test.category === category)
}

export const searchTests = (query: string): LabTest[] => {
  const q = query.toLowerCase()
  return ALL_TESTS.filter(test => 
    test.name.toLowerCase().includes(q) ||
    test.description.toLowerCase().includes(q) ||
    test.id.toLowerCase().includes(q)
  )
}

export const TEST_COUNT = ${tests.length}
`

// Write TypeScript file
const outputPath = join(process.cwd(), 'lib', 'data', 'all-tests.ts')
writeFileSync(outputPath, tsContent, 'utf-8')

console.log(`Generated ${tests.length} tests to ${outputPath}`)
